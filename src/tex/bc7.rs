const WEIGHTS2: [u16; 4] = [0, 21, 43, 64];
const WEIGHTS3: [u16; 8] = [0, 9, 18, 27, 37, 46, 55, 64];
const WEIGHTS4: [u16; 16] = [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64];

pub(super) fn decode(mip: Mip<'_>, output: &mut [u8]) -> Result<(), &'static str> {
    let width = usize::from(mip.width);
    let height = usize::from(mip.height);
    let columns = width.div_ceil(4);
    for (index, block) in mip.data.chunks_exact(16).enumerate() {
        let block: &[u8; 16] = block.try_into().map_err(|_| "truncated BC7 block")?;
        let pixels = decode_block(block)?;
        let origin_x = (index % columns) * 4;
        let origin_y = (index / columns) * 4;
        for (i, rgba) in pixels.into_iter().enumerate() {
            let x = origin_x + i % 4;
            let y = origin_y + i / 4;
            if x >= width || y >= height {
                continue;
            }
            let offset = (y * width + x) * 4;
            output[offset..offset + 4].copy_from_slice(&rgba);
        }
    }
    Ok(())
}

fn decode_block(block: &[u8; 16]) -> Result<[[u8; 4]; PIXELS], &'static str> {
    let bits = u128::from_le_bytes(*block);
    let mode = bits.trailing_zeros() as usize;
    if mode >= MODES.len() {
        return Err("invalid BC7 mode");
    }
    let info = &MODES[mode];
    let mut position = mode + 1;
    let mut read = |count: usize| -> Result<u32, &'static str> {
        if count == 0 {
            return Ok(0);
        }
        if position + count > 128 {
            return Err("truncated BC7 block");
        }
        let value = ((bits >> position) & ((1u128 << count) - 1)) as u32;
        position += count;
        Ok(value)
    };

    let partition = read(info.partition_bits)? as usize;
    let rotation = read(info.rotation_bits)? as usize;
    let index_mode = read(info.index_mode_bits)? as usize;
    let endpoints = (info.partitions + 1) * 2;

    let mut raw = [[0u16; 4]; 6];
    for channel in 0..4 {
        if info.prec[channel] == 0 {
            for color in raw.iter_mut().take(endpoints) {
                color[channel] = 255;
            }
            continue;
        }
        for color in raw.iter_mut().take(endpoints) {
            color[channel] = read(info.prec[channel])? as u16;
        }
    }
    let mut p_bits = [0u16; 6];
    for bit in p_bits.iter_mut().take(info.p_bits) {
        *bit = read(1)? as u16;
    }
    if info.p_bits > 0 {
        for (index, color) in raw.iter_mut().take(endpoints).enumerate() {
            let bit = p_bits[index * info.p_bits / endpoints];
            for (channel, value) in color.iter_mut().enumerate() {
                if info.prec[channel] != info.prec_with_p[channel] {
                    *value = (*value << 1) | bit;
                }
            }
        }
    }
    let mut colors = [[0u8; 4]; 6];
    for (index, color) in raw.iter().enumerate().take(endpoints) {
        for channel in 0..4 {
            colors[index][channel] = unquantize(color[channel], info.prec_with_p[channel]);
        }
    }

    let fixups = &FIXUPS[info.partitions][partition];
    let mut primary = [0u32; PIXELS];
    for (pixel, slot) in primary.iter_mut().enumerate() {
        let anchor = fixups.contains(&(pixel as u8));
        *slot = read(if anchor {
            info.index_prec - 1
        } else {
            info.index_prec
        })?;
    }
    let mut secondary = [0u32; PIXELS];
    if info.index_prec2 > 0 {
        for (pixel, slot) in secondary.iter_mut().enumerate() {
            *slot = read(if pixel == 0 {
                info.index_prec2 - 1
            } else {
                info.index_prec2
            })?;
        }
    }

    let mut pixels = [[0u8; 4]; PIXELS];
    for (pixel, out) in pixels.iter_mut().enumerate() {
        let region = PARTITIONS[info.partitions][partition][pixel] as usize;
        if region * 2 + 1 >= endpoints {
            return Err("BC7 partition exceeds endpoint count");
        }
        let start = colors[region * 2];
        let end = colors[region * 2 + 1];
        let (color_index, alpha_index, color_prec, alpha_prec) = if info.index_prec2 == 0 {
            (
                primary[pixel],
                primary[pixel],
                info.index_prec,
                info.index_prec,
            )
        } else if index_mode == 0 {
            (
                primary[pixel],
                secondary[pixel],
                info.index_prec,
                info.index_prec2,
            )
        } else {
            (
                secondary[pixel],
                primary[pixel],
                info.index_prec2,
                info.index_prec,
            )
        };
        let mut rgba = [0u8; 4];
        for channel in 0..3 {
            rgba[channel] = mix(
                start[channel],
                end[channel],
                weight(color_index, color_prec)?,
            );
        }
        rgba[3] = mix(start[3], end[3], weight(alpha_index, alpha_prec)?);
        match rotation {
            1 => rgba.swap(0, 3),
            2 => rgba.swap(1, 3),
            3 => rgba.swap(2, 3),
            _ => {}
        }
        *out = rgba;
    }
    Ok(pixels)
}

fn weight(index: u32, precision: usize) -> Result<u16, &'static str> {
    let table: &[u16] = match precision {
        2 => &WEIGHTS2,
        3 => &WEIGHTS3,
        4 => &WEIGHTS4,
        _ => return Err("invalid BC7 index precision"),
    };
    table
        .get(index as usize)
        .copied()
        .ok_or("BC7 index exceeds weight table")
}

fn mix(start: u8, end: u8, weight: u16) -> u8 {
    ((u32::from(start) * u32::from(64 - weight) + u32::from(end) * u32::from(weight) + 32) >> 6)
        as u8
}

/// Expands `precision` bits to eight by replicating the high bits.
fn unquantize(value: u16, precision: usize) -> u8 {
    if precision == 0 {
        return 255;
    }
    let expanded = value << (8 - precision);
    (expanded | (expanded >> precision)) as u8
}

